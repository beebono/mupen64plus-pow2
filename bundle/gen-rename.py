#!/usr/bin/env python3
"""Generate per-component rename headers + core_api.list for the static bundle.

usage: gen-rename.py [WORKSPACE]   (default: two dirs above this file)
Writes core_api.list (--dynamic-list) and core_api.ver (--version-script, the same names + local: *) and rename-<p>.h (p = foir armlet altru suxty ui) and core_api.list next to
this script.  Extra per-component renames (symbol clashes found by
check-clashes.py) are read from extra-<p>.txt, one identifier per line.
"""
import re, sys, os, glob

here = os.path.dirname(os.path.abspath(__file__))
ws = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(here))
core = os.path.join(ws, 'mupen64plus-core-dento', 'src', 'api')

def ver_names(path):
    t = open(path).read()
    t = re.sub(r'local:.*', '', t, flags=re.S)
    return re.findall(r'^\s*(\w+)\s*;', t, flags=re.M)

def export_names(srcdir):
    names = set()
    for f in glob.glob(srcdir + '/*.[ch]'):
        for m in re.finditer(r'EXPORT\s+[\w\s\*]+?\bCALL\s+(\w+)\s*\(', open(f, errors='replace').read()):
            names.add(m.group(1))
    return sorted(names)

core_api = ver_names(os.path.join(core, 'api_export.ver'))
ptrs = set()
for h in glob.glob(core + '/m64p_*.h'):
    ptrs |= set(re.findall(r'\(\*ptr_(\w+)\)', open(h).read()))
core_ptrs = sorted((set(core_api) | ptrs) - {'PluginGetVersion'})

comp = {
    'foir':   ver_names(os.path.join(ws, 'mupen64plus-rdp-foir/src/foir_api_export.ver')),
    'armlet': ver_names(os.path.join(ws, 'mupen64plus-rsp-armlet/src/armlet_api_export.ver')),
    'altru':  export_names(os.path.join(ws, 'mupen64plus-audio-altru/src')),
    'suxty':  export_names(os.path.join(ws, 'mupen64plus-input-suxty/src')),
    'ui':     [],
}
# names that are unique already and are looked up by their real name
keep = {'FoirSuxtyGetInterface', 'AltruSuxtyGetInterface'}

for p, api in comp.items():
    api = [a for a in api if a not in keep]
    extra = []
    ef = os.path.join(here, 'extra-%s.txt' % p)
    if os.path.exists(ef):
        extra = [l.split('#')[0].strip() for l in open(ef)]
        extra = [l for l in extra if l]
    names = []
    for n in api + core_ptrs + extra:
        if n not in names:
            names.append(n)
    with open(os.path.join(here, 'rename-%s.h' % p), 'w') as o:
        o.write('/* generated by gen-rename.py: static bundle symbol prefix "%s_" */\n' % p)
        o.write('#ifndef BUNDLE_RENAME_%s_H\n#define BUNDLE_RENAME_%s_H\n' % (p.upper(), p.upper()))
        for n in names:
            o.write('#define %s %s_%s\n' % (n, p, n))
        o.write('#endif\n')

with open(os.path.join(here, 'core_api.list'), 'w') as o:
    o.write('{\n')
    for n in sorted(set(core_api) | {'CoreStaticPluginHandle', 'CoreStaticPluginGetProc'}):
        o.write('  %s;\n' % n)
    o.write('};\n')
with open(os.path.join(here, 'core_api.ver'), 'w') as o:
    o.write('{ global:\n')
    for n in sorted(set(core_api) | {'CoreStaticPluginHandle', 'CoreStaticPluginGetProc'}):
        o.write('%s;\n' % n)
    o.write('local: *; };\n')
print('core api %d, core ptr names %d' % (len(core_api), len(core_ptrs)),
      {p: len(a) for p, a in comp.items()})
